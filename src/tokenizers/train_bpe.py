"""Byte-level BPE tokenizer per encoding x training dataset, trained on the TRAIN split only (plan §6.2).

Usage (from the repo root):
    uv run python -m src.tokenizers.train_bpe --config configs/bert_small.yaml [--encoding X] [--dataset Y]

Saves <tokenizer.dir>/<encoding>/<dataset>/{tokenizer.json, meta.json}. meta.json holds max_len: the token
length (incl. [CLS]/[SEP]) that covers `coverage_percentile` % of train rows. Longer rows are truncated.
"""

import argparse
import json
import logging
from pathlib import Path

import numpy as np
from tokenizers import Tokenizer, decoders, models, pre_tokenizers, processors, trainers

from src.config import load_bert_config, split_roles
from src.data.processed import load_splits
from src.encoders import encode_split

log = logging.getLogger("bpe")


def train_tokenizer(texts, tk):
    sp = tk["special_tokens"]
    tok = Tokenizer(models.BPE(unk_token=sp["unk"]))
    tok.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
    tok.decoder = decoders.ByteLevel()
    trainer = trainers.BpeTrainer(vocab_size=tk["vocab_size"], min_frequency=tk["min_frequency"],
                                  special_tokens=[sp["pad"], sp["unk"], sp["cls"], sp["sep"]],
                                  initial_alphabet=pre_tokenizers.ByteLevel.alphabet(), show_progress=False)
    tok.train_from_iterator(texts, trainer)
    tok.post_processor = processors.TemplateProcessing(
        single=f"{sp['cls']} $A {sp['sep']}",
        special_tokens=[(sp["cls"], tok.token_to_id(sp["cls"])), (sp["sep"], tok.token_to_id(sp["sep"]))])
    return tok


def token_lengths(tok, texts):
    return np.array([len(e.ids) for e in tok.encode_batch(texts)])


def tokenizer_dir(cfg, encoding, dataset):
    return Path(cfg["tokenizer"]["dir"]) / encoding / dataset


def is_done(cfg, encoding, dataset):
    """The tokenizer for (encoding, training dataset) exists (used by src/run.py)."""
    return (tokenizer_dir(cfg, encoding, dataset) / "meta.json").exists()


def load_tokenizer(cfg, encoding, dataset):
    """(tokenizer with truncation at max_len, meta dict) for a training dataset."""
    d = tokenizer_dir(cfg, encoding, dataset)
    if not (d / "tokenizer.json").exists():
        raise FileNotFoundError(f"{d} missing; run `python -m src.tokenizers.train_bpe` first")
    meta = json.loads((d / "meta.json").read_text())
    tok = Tokenizer.from_file(str(d / "tokenizer.json"))
    tok.enable_truncation(meta["max_len"])
    return tok, meta


def build_one(cfg, encoding, dataset):
    train = load_splits(cfg["data"], dataset)[split_roles(cfg["data"])[0]]
    texts = encode_split(cfg["enc"], encoding, dataset, train)
    tok = train_tokenizer(texts, cfg["tokenizer"])
    lengths = token_lengths(tok, texts)
    pct = cfg["tokenizer"]["coverage_percentile"]
    max_len = int(np.ceil(np.percentile(lengths, pct)))
    meta = {"encoding": encoding, "dataset": dataset, "vocab_size": tok.get_vocab_size(), "max_len": max_len,
            "coverage_percentile": pct, "n_train": len(texts), "p50": int(np.percentile(lengths, 50)),
            "max": int(lengths.max()), "share_truncated": round(float(np.mean(lengths > max_len)), 4)}
    d = tokenizer_dir(cfg, encoding, dataset)
    d.mkdir(parents=True, exist_ok=True)
    tok.save(str(d / "tokenizer.json"))
    (d / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    return meta


def render_markdown(cfg, metas):
    names = {d: cfg["data"]["dataset_configs"][d]["name"] for d in cfg["data"]["datasets"]}
    tk = cfg["tokenizer"]
    lines = ["# Tokenizer statistics", "",
             (f"Byte-level BPE (vocab {tk['vocab_size']}, min frequency {tk['min_frequency']}) per encoding x "
              f"training dataset, trained on the train split. max_len covers {tk['coverage_percentile']}% of train "
              "rows (tokens incl. [CLS]/[SEP]). Generated by `src/tokenizers/train_bpe.py`."), "",
             "| Encoding | Dataset | Vocab | Tokens p50 | max_len | Max | Truncated |",
             "| --- | --- | ---: | ---: | ---: | ---: | ---: |"]
    for m in metas:
        lines.append(f"| {m['encoding']} | {names[m['dataset']]} | {m['vocab_size']} | {m['p50']} | {m['max_len']} | "
                     f"{m['max']} | {100 * m['share_truncated']:.2f}% |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", required=True, help="e.g. configs/bert_small.yaml")
    parser.add_argument("--encoding")
    parser.add_argument("--dataset")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s", datefmt="%H:%M:%S")
    cfg = load_bert_config(args.config)
    encodings = [args.encoding] if args.encoding else cfg["encodings"]
    datasets = [args.dataset] if args.dataset else cfg["data"]["datasets"]
    for enc in encodings:
        for ds in datasets:
            m = build_one(cfg, enc, ds)
            log.info("[%s/%s] vocab %d, p50 %d, max_len %d, truncated %.2f%%", enc, ds, m["vocab_size"], m["p50"],
                     m["max_len"], 100 * m["share_truncated"])

    metas = [json.loads((tokenizer_dir(cfg, e, d) / "meta.json").read_text())
             for e in cfg["encodings"] for d in cfg["data"]["datasets"] if (tokenizer_dir(cfg, e, d) / "meta.json").exists()]
    out = cfg["outputs"]
    Path(out["tokenizer_stats_json"]).write_text(json.dumps(metas, indent=2) + "\n")
    Path(out["tokenizer_stats_md"]).write_text(render_markdown(cfg, metas))
    log.info("wrote %s", out["tokenizer_stats_md"])


if __name__ == "__main__":
    main()
