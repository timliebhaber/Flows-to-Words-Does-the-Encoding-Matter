# ---- tables: {"title", "headers", "rows": [(label, [cell])], "col_metrics", "note"}; cell = Ref | str ----

@dataclass(frozen=True)
class Ref:
    """A table cell showing the report number `key` (see src/eval/numbers.py).

    LaTeX gets `\\resor{key}{pending}` (or `tex`, e.g. a `\\resdiff`), so no number is written into the report;
    Markdown gets the value itself: `stat` formatted, or `text`. `stat` also decides the bold best cell."""
    key: str
    stat: Stat | None = None
    text: str = ""
    tex: str = ""


def _best(rows, col, metric, lower_is_better):
    values = [cells[col].stat.mean for _, cells in rows if isinstance(cells[col], Ref) and cells[col].stat is not None]
    if metric is None or not values:
        return None
    return min(values) if metric in lower_is_better else max(values)


def _cell_text(cell, fmt, tex):
    if isinstance(cell, str):
        return tex_escape(cell) if tex else cell
    if tex:
        return cell.tex or rf"\resor{{{cell.key}}}{{{tex_escape(fmt['pending'])}}}"
    return cell.text or fmt_stat(cell.stat, fmt)


def _rendered_rows(table, fmt, tex):
    best = [_best(table["rows"], c, m, fmt["lower_is_better"]) for c, m in enumerate(table["col_metrics"])]
    out = []
    for label, cells in table["rows"]:
        texts = []
        for c, cell in enumerate(cells):
            s = _cell_text(cell, fmt, tex)
            if best[c] is not None and isinstance(cell, Ref) and cell.stat is not None and cell.stat.mean == best[c]:
                s = rf"\textbf{{{s}}}" if tex else f"**{s}**"
            texts.append(s)
        out.append([tex_escape(label) if tex else label] + texts)
    return out


def render_md(table, fmt):
    head = table["headers"]
    lines = [f"## {table['title']}", "", "| " + " | ".join(head) + " |",
             "|" + "|".join(["---"] + ["---:"] * (len(head) - 1)) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in _rendered_rows(table, fmt, tex=False)]
    return "\n".join(lines + ["", table["note"], ""])


def render_tex(table, fmt):
    head = table["headers"]
    lines = [(f"% {table['title']}: generated by src/eval/analysis.py, do not edit. Cells are \\resor/\\resdiff macros "
             "(values in numbers_analysis.tex)."), r"\begin{tabular}{l" + "r" * (len(head) - 1) + "}", r"\toprule",
             " & ".join(tex_escape(h) for h in head) + r" \\", r"\midrule"]
    lines += [" & ".join(r) + r" \\" for r in _rendered_rows(table, fmt, tex=True)]
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular}", ""])


def write_table(stem, table, long_df, fmt, tex_dir):
    """<stem>.md and <stem>.csv, plus the LaTeX version as <tex_dir>/<stem name>.tex (inside the report)."""
    stem, tex = Path(stem), Path(tex_dir) / f"{Path(stem).name}.tex"
    for p in (stem, tex):
        p.parent.mkdir(parents=True, exist_ok=True)
    stem.with_suffix(".md").write_text(render_md(table, fmt))
    tex.write_text(render_tex(table, fmt))
    long_df.to_csv(stem.with_suffix(".csv"), index=False)
    return [stem.with_suffix(".md"), tex, stem.with_suffix(".csv")]


def _long(cells, keys, metric):
    return pd.DataFrame([{**dict(zip(keys, k)), "metric": metric, "mean": s.mean, "std": s.std, "n_seeds": s.n}
                         for k, s in cells.items()])


def _seed_note(cfg, cells, model_of=lambda k: k[0]):
    fmt = cfg["format"]
    counts = {}
    for k, s in cells.items():
        counts.setdefault(model_of(k), set()).add(s.n)
    parts = [f"{cfg['models'][m]} {'/'.join(map(str, sorted(counts[m])))}" for m in cfg["models"] if m in counts]
    note = (f"Mean ± std over seeds; {fmt['one_seed_marker']} = 1 seed (no std); bold = best per column; "
            f"'{fmt['pending']}' = no results yet.")
    return note + (f" Seeds per cell: {', '.join(parts)}." if fmt["max_seeds_note"] and parts else "")


# ---- table builders ----

def exp2_table(cfg, within, metric):
    keys = ["model", "encoding", "test_dataset"]
    cells = cell_stats(within, keys, metric, cfg["format"]["std_ddof"])
    rows = [(m["label"], [Ref(f"exp2.{m['model']}.{m['encoding']}.{d}.{metric}", cells.get((m["model"], m["encoding"], d)))
                          for d in cfg["datasets"]]) for m in cfg["methods"]]
    label = cfg["format"]["metric_labels"][metric]
    table = {"title": f"Experiment 2: within-dataset test {label} (multiclass)",
             "headers": ["Method"] + list(cfg["datasets"].values()), "rows": rows,
             "col_metrics": [metric] * len(cfg["datasets"]), "note": _seed_note(cfg, cells)}
    return table, cells, _long(cells, keys, metric)


def side_runs_table(cfg, within, metric):
    sr, fmt = cfg["side_runs"], cfg["format"]
    keys = ["model", "encoding", "test_dataset"]
    cells = cell_stats(within, keys, metric, fmt["std_ddof"])
    rows, records = [], []
    for (model, enc, dataset), side in sorted(cells.items()):
        if enc not in sr["encodings"]:
            continue
        main = cells.get((model, sr["encodings"][enc], dataset))
        main_key = f"exp2.{model}.{sr['encodings'][enc]}.{dataset}.{metric}"
        side_key = f"exp2.{model}.{enc}.{dataset}.{metric}"
        delta = "" if main is None else Ref("", text=f"{side.mean - main.mean:+.{fmt['decimals']}f}",
                                            tex=rf"\resdiff{{{side_key}}}{{{main_key}}}")
        rows.append((f"{cfg['models'][model]} {cfg['encodings'][sr['encodings'][enc]]}, {cfg['datasets'][dataset]}",
                     [Ref(main_key, main), Ref(side_key, side), delta]))
        records.append({"model": model, "encoding": enc, "main_encoding": sr["encodings"][enc], "dataset": dataset,
                        "metric": metric, "main_mean": None if main is None else main.mean, "side_mean": side.mean,
                        "side_n_seeds": side.n})
    label = fmt["metric_labels"][metric]
    table = {"title": f"Side runs: does truncating PPFLE text cost {label}?",
             "headers": ["Run", sr["main_label"], sr["side_label"], "Difference"], "rows": rows,
             "col_metrics": [None, None, None],
             "note": _seed_note(cfg, {k: s for k, s in cells.items() if k[0] in {r["model"] for r in records}
                                      and (k[1] in sr["encodings"] or k[1] in sr["encodings"].values())})}
    return table, pd.DataFrame(records)


def not_planned(cfg):
    """{(model, encoding, version)} of text-model runs that are never planned, from `dataset_encodings` in the model
    configs listed under replication.planned_from (a version listed there runs only the encodings given)."""
    out = set()
    for model, path in cfg["replication"]["planned_from"].items():
        planned = _read_yaml(path).get("dataset_encodings", {})
        for version, encodings in planned.items():
            out |= {(model, m["encoding"], version) for m in cfg["methods"]
                    if m["model"] == model and m["encoding"] not in encodings}
    return out


def exp1_table(cfg, df):
    rep, fmt = cfg["replication"], cfg["format"]
    skip = not_planned(cfg)
    rows_df = replication_rows(df, cfg)
    keys = ["model", "encoding", "test_dataset", "task"]
    per_metric = {m: cell_stats(rows_df, keys, m, fmt["std_ddof"]) for m in rep["metrics"]}
    cols = [(v, m) for v in rep["versions"] for m in rep["metrics"]]
    rows = []
    for meth in cfg["methods"]:
        for task in rep["tasks"]:
            cells = [fmt["not_run"] if (meth["model"], meth["encoding"], v) in skip else
                     Ref(f"exp1.{meth['model']}.{meth['encoding']}.{v}.{task}.{m}",
                         per_metric[m].get((meth["model"], meth["encoding"], v, task))) for v, m in cols]
            if any(isinstance(c, Ref) and c.stat is not None for c in cells):
                rows.append((f"{meth['label']} ({task})", cells))
    paper = rep["paper"]
    rows.append((paper["label"], [Ref("exp1.paper.accuracy", text=f"{paper['accuracy']:.{fmt['decimals']}f}")
                                  if (v, m) == (paper["version"], "accuracy") else "" for v, m in cols]))
    table = {"title": "Experiment 1: replication on Edge-IIoTset",
             "headers": ["Method"] + [f"{rep['versions'][v]}: {fmt['metric_labels'][m]}" for v, m in cols],
             "rows": rows, "col_metrics": [None] * len(cols),   # no bold: rows mix tasks
             "note": _seed_note(cfg, per_metric[rep["metrics"][0]])}
    long_df = pd.concat([_long(c, keys, m) for m, c in per_metric.items()], ignore_index=True)
    replication = {}
    for m, cells in per_metric.items():
        for k, s in cells.items():
            replication.setdefault(k, {})[m] = s
    return table, long_df, replication


def exp3_tables(cfg, df):
    fmt, cross = cfg["format"], cfg["cross"]
    rows_df = cross_rows(df, cfg)
    summary = {m: cross_summary(rows_df, cross["datasets"], m, fmt["std_ddof"]) for m in cross["metrics"]}
    cell_keys = ["model", "encoding", "train_dataset", "test_dataset"]
    cells = {m: cell_stats(rows_df, cell_keys, m, fmt["std_ddof"]) for m in cross["metrics"]}
    cols = [(m, part) for m in cross["metrics"] for part in ("diag", "off")]
    rows = []
    for meth in cfg["methods"]:
        key = (meth["model"], meth["encoding"])
        if any(key in summary[m] for m in cross["metrics"]):
            rows.append((meth["label"], [Ref(f"exp3.{key[0]}.{key[1]}.{part}.{m}",
                                             summary[m][key][part] if key in summary[m] else None) for m, part in cols]))
    names = {"diag": "same dataset", "off": "off-diagonal"}
    table = {"title": "Experiment 3: cross-dataset transfer (binary), mean over the train x test grid",
             "headers": ["Method"] + [f"{fmt['metric_labels'][m]} {names[p]}" for m, p in cols], "rows": rows,
             "col_metrics": [m for m, _ in cols],
             "note": (f"Off-diagonal = trained on one dataset, tested on another (the generalisation number). Per "
                      f"seed, the {len(cross['datasets'])} diagonal and {len(cross['datasets']) ** 2 - len(cross['datasets'])} "
                      "off-diagonal cells are averaged first. ")
                     + _seed_note(cfg, {k: v["off"] for k, v in summary[cross["metrics"][0]].items()})}
    summary_long = pd.DataFrame([{"model": k[0], "encoding": k[1], "metric": m, "part": p, "mean": v[p].mean,
                                  "std": v[p].std, "n_seeds": v[p].n}
                                 for m, s in summary.items() for k, v in s.items() for p in ("diag", "off")])
    cells_long = pd.concat([_long(c, cell_keys, m) for m, c in cells.items()], ignore_index=True)
    return table, summary, cells, summary_long, cells_long


# ---- error analysis ----

def error_analysis(cfg, within, primary_cells):
    """Markdown report + figures from run_details. Returns (markdown, figure stems, aggregates)."""
    fmt, err, fc = cfg["format"], cfg["errors"], cfg["figures"]
    aggs = aggregate_details(within, cfg["inputs"]["run_details_dir"])
    labels = {(m["model"], m["encoding"]): m["label"] for m in cfg["methods"]}
    d = fmt["decimals"]
    lines = ["# Error analysis (multiclass, within dataset)", "",
             ("From `results/run_details/`: per-class F1 is the mean over seeds; confusion counts are summed over "
             f"seeds. Confusion matrices: XGBoost and the best encoding (by mean test macro-F1) of each text model. "
             f"Hard class = even the best method stays below per-class F1 {err['hard_class_f1']}."), ""]
    stems = []
    for dataset, name in cfg["datasets"].items():
        entries = [(labels[k], aggs[(*k, dataset)]) for k in labels if (*k, dataset) in aggs]
        if not entries:
            lines += [f"## {name}", "", f"{fmt['pending']}", ""]
            continue
        classes = entries[0][1]["classes"]
        lines += [f"## {name}", "", "Per-class F1:", "", "| Method | " + " | ".join(classes) + " |",
                  "|" + "|".join(["---"] + ["---:"] * len(classes)) + "|"]
        for label, agg in entries:
            lines.append(f"| {label} | " + " | ".join(f"{v:.{d}f}" for v in agg["per_class_f1"]) + " |")
        hard = hard_classes(dict(entries), err["hard_class_f1"])
        lines += ["", "Hard classes: " + (", ".join(f"{c} (best F1 {f:.{d}f})" for c, f in hard) or "none"), ""]
        chosen = []
        for model in err["confusion_models"]:
            own = {k: s for k, s in primary_cells.items() if k[0] == model and k[2] == dataset and (k[0], k[1]) in labels}
            if own:
                best = max(own, key=lambda k: own[k].mean)
                if best in aggs:
                    chosen.append((f"{labels[best[:2]]} ({fmt_stat(own[best], fmt)})", aggs[best]))
        for label, agg in chosen:
            lines += [f"Top mix-ups, {label}:", ""]
            lines += [f"- {t} → {p}: {s:.1%} of {t} ({c} rows)"
                      for t, p, s, c in top_confusions(agg["confusion"], agg["classes"], err["top_confusions"])]
            lines.append("")
        stems += figures.perclass_heatmap(cfg, dataset, entries)
        if chosen:
            stems += figures.confusion_panels(cfg, dataset, chosen)
    lines += ["Figures: " + ", ".join(f"`{fc['dir']}/{s}.*`" for s in stems), ""]
    return "\n".join(lines), stems, aggs


# ---- encoding examples ----

def encoding_examples(cfg):
    """LaTeX table with the same flow in every encoding (cut at `max_chars`); [] if the encoder stats are missing."""
    ex = cfg["examples"]
    source = Path(ex["source"])
    if not source.exists():
        return []
    example = json.loads(source.read_text())["example"]
    lines = ["% One flow in every encoding: generated by src/eval/analysis.py from " + ex["source"] + ", do not edit.",
             r"\begin{tabular}{@{}l p{" + ex["text_width"] + r"}@{}}", r"\toprule", r"Encoding & Text \\", r"\midrule"]
    for enc, label in cfg["encodings"].items():
        if enc not in example:
            continue
        text = example[enc]
        cut = len(text) > ex["max_chars"]
        if cut:
            text = text[:ex["max_chars"]].rsplit(" ", 1)[0]
        body = tex_escape(text) + (r" \dots" if cut else "")
        if enc in ex["monospace"]:
            body = r"\texttt{\small " + body + "}"
        lines.append(f"{tex_escape(label)} & {body} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    path = Path(ex["tex"])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return [path]


