"""Single-feature leakage check (plan §4.4): XGBoost on one feature at a time, train -> val.

A feature that alone reaches macro-F1 above `leakage.flag_threshold` must be investigated.

Usage (from the repo root):
    uv run python -m src.eval.leakage --config configs/xgb.yaml [--dataset nf_unsw_nb15]
"""

import argparse
import json
import logging
import time
from pathlib import Path

from src.config import load_model_config, split_roles
from src.data.processed import class_names, encode_target, load_splits, model_frame
from src.eval.metrics import compute_metrics
from src.models.xgb import fit

log = logging.getLogger("leakage")


def single_feature_scores(train_df, eval_df, features, string_features, target_col, benign, lk, eval_metric):
    """{feature: macro-F1 on eval_df} for a model trained on that feature alone."""
    names = class_names(train_df, target_col)
    y_tr = encode_target(train_df, target_col, names)
    y_ev = encode_target(eval_df, target_col, names)
    scores = {}
    for f in features:
        X_tr, X_ev = (model_frame(df, [f], string_features, train_df) for df in (train_df, eval_df))
        model, _ = fit(X_tr, y_tr, None, None, lk["params"], lk["seed"], lk["class_weight"], eval_metric)
        scores[f] = compute_metrics(y_ev, model.predict(X_ev), names, benign)["macro_f1"]
    return scores


def flagged(scores, threshold):
    return sorted(f for f, s in scores.items() if s > threshold)


def render_markdown(results, dataset_names, threshold, eval_split):
    """One table: features x (dataset, task), sorted by the best score of each feature."""
    keys = [(d, t) for d in results for t in results[d]]
    first_task_scores = next(iter(next(iter(results.values())).values()))
    features = list(first_task_scores)
    best = {f: max(results[d][t][f] for d, t in keys) for f in features}
    header = ["Feature"] + [f"{dataset_names[d]} {t}" for d, t in keys]
    lines = ["# Single-feature leakage check", "",
             (f"XGBoost trained on ONE feature at a time (train split), macro-F1 on the {eval_split} split. "
              f"Bold = above {threshold} (investigate). Generated by `src/eval/leakage.py`."), "",
             "| " + " | ".join(header) + " |", "| --- |" + " ---: |" * len(keys)]
    for f in sorted(features, key=lambda f: -best[f]):
        cells = []
        for d, t in keys:
            s = results[d][t][f]
            cells.append(f"**{s:.3f}**" if s > threshold else f"{s:.3f}")
        lines.append(f"| {f} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def is_done(cfg, dataset):
    """`dataset` has single-feature scores for every task (used by src/run.py)."""
    path = Path(cfg["outputs"]["leakage_json"])
    done = json.loads(path.read_text()).get(dataset, {}) if path.exists() else {}
    return all(task in done for task in cfg["tasks"])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", required=True, help="model config YAML, e.g. configs/xgb.yaml")
    parser.add_argument("--dataset", help="one dataset (default: all in the data config)")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s", datefmt="%H:%M:%S")
    cfg = load_model_config(args.config)
    data, lk, out = cfg["data"], cfg["leakage"], cfg["outputs"]
    if args.dataset and args.dataset not in data["datasets"]:
        parser.error(f"unknown dataset {args.dataset!r}; choose from {data['datasets']}")
    train_split = split_roles(data)[0]

    path = Path(out["leakage_json"])
    results = json.loads(path.read_text()) if path.exists() else {}
    for dataset in [args.dataset] if args.dataset else data["datasets"]:
        splits = load_splits(data, dataset)
        for task, spec in cfg["tasks"].items():
            t0 = time.time()
            scores = single_feature_scores(splits[train_split], splits[lk["eval_split"]], data["columns"]["features"],
                                           data["columns"]["string_features"], data["columns"][spec["target"]], data["columns"][spec["benign"]], lk,
                                           spec["eval_metric"])
            results.setdefault(dataset, {})[task] = scores
            top = sorted(scores.items(), key=lambda kv: -kv[1])[:3]
            log.info("[%s/%s] %.0fs; top: %s; flagged: %s", dataset, task, time.time() - t0,
                     [(f, round(s, 3)) for f, s in top], flagged(scores, lk["flag_threshold"]))
        path.write_text(json.dumps(results, indent=2) + "\n")  # save after each dataset

    ordered = {d: results[d] for d in data["datasets"] if d in results}
    names = {d: data["dataset_configs"][d]["name"] for d in ordered}
    Path(out["leakage_md"]).write_text(render_markdown(ordered, names, lk["flag_threshold"], lk["eval_split"]))
    log.info("wrote %s and %s", out["leakage_json"], out["leakage_md"])


if __name__ == "__main__":
    main()
