"""Fit encoder state on each dataset's TRAIN split and report text lengths.

Usage (from the repo root):
    uv run python -m src.encoders.build --config configs/encoders.yaml

Writes the E2 bin edges (<binning.state_dir>/<dataset>.json) and results/encoding_stats.{json,md}:
characters, whitespace tokens and DistilBERT WordPiece tokens per encoding x dataset, measured on train only.
"""

import argparse
import json
import logging
import time
from pathlib import Path

import numpy as np
from transformers import AutoTokenizer

from src import encoders
from src.config import load_encoder_config, split_roles
from src.data.processed import load_splits
from src.encoders import ppfle_binned

log = logging.getLogger("encoders")


def _summary(lengths, percentiles):
    arr = np.asarray(lengths)
    return {"mean": round(float(arr.mean()), 1), **{f"p{p}": int(np.percentile(arr, p)) for p in percentiles},
            "max": int(arr.max())}


def dataset_stats(cfg, dataset, tokenizer):
    rep = cfg["length_report"]
    train = load_splits(cfg["data"], dataset)[split_roles(cfg["data"])[0]]
    sample_idx = np.random.default_rng(rep["seed"]).choice(len(train), min(rep["sample_rows"], len(train)),
                                                           replace=False)
    out = {"n_train": len(train), "encodings": {}}
    for enc in cfg["encodings"]:
        t0 = time.time()
        state = encoders.fit_state(cfg, enc, train)
        if state is not None:
            ppfle_binned.save_state(state, cfg, dataset)
            out["e2_bins_per_column"] = {c: len(e) + 1 for c, e in state["edges"].items()}
        texts = encoders.encode(cfg, enc, train, state)
        wp = [len(ids) for ids in tokenizer([texts[i] for i in sample_idx])["input_ids"]]
        out["encodings"][enc] = {
            "chars": _summary([len(t) for t in texts], rep["percentiles"]),
            "words": _summary([len(t.split()) for t in texts], rep["percentiles"]),
            "wordpiece_tokens": _summary(wp, rep["percentiles"]),
            "share_over_model_max": round(float(np.mean(np.asarray(wp) > rep["model_max_length"])), 4),
            "encode_seconds": round(time.time() - t0, 1),
        }
        log.info("[%s/%s] wordpiece %s", dataset, enc, out["encodings"][enc]["wordpiece_tokens"])
    return out


def render_markdown(cfg, stats, example):
    rep = cfg["length_report"]
    names = {d: cfg["data"]["dataset_configs"][d]["name"] for d in stats}
    pct = [f"p{p}" for p in rep["percentiles"]]
    lines = ["# Encoding statistics", "",
             (f"Measured on the train split. WordPiece = `{rep['tokenizer']}` tokens incl. [CLS]/[SEP] on "
              f"{rep['sample_rows']:,} sampled rows per dataset; its limit is {rep['model_max_length']}. "
              "Generated by `src/encoders/build.py`."), "",
             "| Dataset | Encoding | Words " + " ".join(f"{p} |" for p in pct) + " WordPiece "
             + " | ".join(pct + ["max"]) + f" | > {rep['model_max_length']} |",
             "| --- | --- |" + " ---: |" * (2 * len(pct) + 2)]
    for d, st in stats.items():
        for enc, s in st["encodings"].items():
            w, t = s["words"], s["wordpiece_tokens"]
            lines.append(f"| {names[d]} | {enc} | " + " | ".join(str(w[p]) for p in pct) + " | "
                         + " | ".join(str(t[p]) for p in pct + ["max"]) + f" | {100 * s['share_over_model_max']:.1f}% |")
    lines += ["", f"## E2 effective bins per numeric column (configured n_bins = {cfg['binning']['n_bins']})", "",
              "| Column | " + " | ".join(names[d] for d in stats) + " |", "| --- |" + " ---: |" * len(stats)]
    for c in ppfle_binned.numeric_columns(cfg):
        lines.append(f"| {c} | " + " | ".join(str(stats[d]["e2_bins_per_column"][c]) for d in stats) + " |")
    ex = rep["example"]
    lines += ["", f"## Example: {names.get(ex['dataset'], ex['dataset'])} train row {ex['row']}", ""]
    for enc, text in example.items():
        lines += [f"**{enc}**", "", "```", text, "```", ""]
    return "\n".join(lines)


def is_done(cfg):
    """E2 bin edges for every dataset and the length report exist (used by src/run.py)."""
    files = [ppfle_binned.state_path(cfg, d) for d in cfg["data"]["datasets"]] + [Path(cfg["outputs"]["stats_json"])]
    return all(f.exists() for f in files)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", required=True, help="encoder config YAML, e.g. configs/encoders.yaml")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s", datefmt="%H:%M:%S")
    cfg = load_encoder_config(args.config)
    tokenizer = AutoTokenizer.from_pretrained(cfg["length_report"]["tokenizer"])

    stats = {d: dataset_stats(cfg, d, tokenizer) for d in cfg["data"]["datasets"]}
    ex = cfg["length_report"]["example"]
    row = load_splits(cfg["data"], ex["dataset"])[split_roles(cfg["data"])[0]].iloc[[ex["row"]]]
    example = {enc: encoders.encode_split(cfg, enc, ex["dataset"], row)[0] for enc in cfg["encodings"]}

    out = cfg["outputs"]
    Path(out["stats_json"]).write_text(json.dumps({"stats": stats, "example": example}, indent=2) + "\n")
    Path(out["stats_md"]).write_text(render_markdown(cfg, stats, example))
    log.info("wrote %s and %s", out["stats_json"], out["stats_md"])


if __name__ == "__main__":
    main()
