"""Dataset statistics: per-dataset JSON plus one combined Markdown file for the report."""

import json
from pathlib import Path


def value_counts(series):
    return {str(k): int(v) for k, v in series.value_counts().items()}


def build_stats(dataset, ds_cfg, settings, raw_counts, targets, sampled, deduped, dedupe_info,
                small_dropped, splits, cols, inf_counts, mapped_counts):
    class_col, label_col = cols["class"], cols["label"]
    final_rows = sum(len(part) for part in splits.values())
    return {
        "dataset": dataset,
        "name": ds_cfg["name"],
        "raw_file": ds_cfg["raw_file"],
        "settings": settings,
        "rows": {
            "raw": int(sum(raw_counts.values())),
            "sampled": len(sampled),
            "exact_duplicates_removed": dedupe_info["exact_duplicates_removed"],
            "conflict_rows": dedupe_info["conflict_rows"],
            "conflict_rows_removed": dedupe_info["conflict_rows_removed"],
            "after_dedupe": len(deduped),
            "small_class_rows_dropped": int(sum(small_dropped.values())),
            "final": final_rows,
            **{name: len(part) for name, part in splits.items()},
        },
        "classes_kept_whole": sorted(c for c, n in raw_counts.items() if targets[c] == n),
        "small_classes_dropped": small_dropped,
        "classes_lost_in_dedupe": sorted(set(raw_counts) - set(deduped[class_col])),
        "class_counts": {
            "raw": {c: int(n) for c, n in raw_counts.items()},
            "target": {c: int(n) for c, n in targets.items()},
            "sampled": value_counts(sampled[class_col]),
            "after_dedupe": value_counts(deduped[class_col]),
            **{name: value_counts(part[class_col]) for name, part in splits.items()},
        },
        "binary_counts": {name: value_counts(part[label_col]) for name, part in splits.items()},
        "na_counts": {c: int(n) for c, n in sampled[cols["features"]].isna().sum().items() if n},
        "inf_counts": inf_counts,  # measured before any inf -> missing conversion
        "string_values_mapped": mapped_counts,  # values rewritten by the dataset's string_value_map, per column
    }


def dataset_stats_path(stats_dir, dataset):
    return Path(stats_dir) / f"{dataset}.json"


def write_dataset_stats(stats, stats_dir):
    Path(stats_dir).mkdir(parents=True, exist_ok=True)
    path = dataset_stats_path(stats_dir, stats["dataset"])
    path.write_text(json.dumps(stats, indent=2) + "\n")
    return path


def _row(cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def _table(header, rows, right_from):
    align = ["---" if i < right_from else "---:" for i in range(len(header))]
    return "\n".join([_row(header), _row(align)] + [_row(r) for r in rows])


def _fmt(n):
    return f"{n:,}"


def render_markdown(all_stats, split_names, benign_label_value):
    out = ["# Dataset statistics", "",
           ("Generated by `src/data/pipeline.py`; do not edit by hand. "
           "Counts are rows. Sampling is stratified by class; classes marked * were kept whole."), ""]

    header = ["Dataset", "Raw", "Sampled", "Exact dups removed", "Conflict rows removed",
              "Small-class rows dropped", "Final"] + [s.capitalize() for s in split_names] + ["Benign % (final)", "Classes"]
    rows = []
    for st in all_stats:
        r = st["rows"]
        benign = sum(st["binary_counts"][s].get(str(benign_label_value), 0) for s in split_names)
        n_classes = len(st["class_counts"][split_names[0]])
        rows.append([st["name"], _fmt(r["raw"]), _fmt(r["sampled"]), _fmt(r["exact_duplicates_removed"]),
                     _fmt(r["conflict_rows_removed"]), _fmt(r["small_class_rows_dropped"]), _fmt(r["final"])]
                    + [_fmt(r[s]) for s in split_names] + [f"{100 * benign / r['final']:.1f}", n_classes])
    out += ["## Overview", "", _table(header, rows, 1), ""]

    for st in all_stats:
        s = st["settings"]
        cc = st["class_counts"]
        out += [f"## {st['name']}", "",
                (f"File `{st['raw_file']}`; sample_size {_fmt(s['sample_size'])}, "
                f"rare_class_threshold {_fmt(s['rare_class_threshold'])}, "
                f"keep_all_classes {s['keep_all_classes'] or 'none'}, conflict_policy `{s['conflict_policy']}`, "
                f"seeds {s['seeds']}."), ""]
        header = ["Class", "Raw", "Sampled", "After dedupe"] + [x.capitalize() for x in split_names]
        rows = []
        for c in sorted(cc["raw"], key=lambda c: -cc["raw"][c]):
            mark = "*" if c in st["classes_kept_whole"] else ""
            rows.append([c + mark, _fmt(cc["raw"][c]), _fmt(cc["sampled"].get(c, 0)),
                         _fmt(cc["after_dedupe"].get(c, 0))] + [_fmt(cc[x].get(c, 0)) for x in split_names])
        out += [_table(header, rows, 1), ""]
        if st["classes_lost_in_dedupe"]:
            out += [f"Classes lost in dedupe (all rows were duplicates/conflicts): {st['classes_lost_in_dedupe']}", ""]
        if st["small_classes_dropped"]:
            out += [f"Dropped after dedupe (too small to stratify): {st['small_classes_dropped']}", ""]
        if st["inf_counts"]:
            converted = " (converted to missing)" if s["inf_to_missing"] else ""
            out += [f"Infinite values in sample{converted}: {st['inf_counts']}", ""]
        if st.get("string_values_mapped"):  # .get: stats written before this field existed
            out += [(f"Text values rewritten by `string_value_map` {s['string_value_map']} in the sample: "
                     f"{st['string_values_mapped']}"), ""]
        if st["na_counts"]:
            out += [f"Missing values in sample (after cleaning): {st['na_counts']}", ""]
    return "\n".join(out)


def write_summary(stats_dir, dataset_order, summary_file, split_names, benign_label_value):
    """Rebuild the combined Markdown from every <dataset>.json present, in config order."""
    paths = [Path(stats_dir) / f"{d}.json" for d in dataset_order]
    all_stats = [json.loads(p.read_text()) for p in paths if p.exists()]
    Path(summary_file).write_text(render_markdown(all_stats, split_names, benign_label_value))
    return summary_file
